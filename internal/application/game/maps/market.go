// wiki: Trade, Faction base: a visited settlement restocks after 30 days,
// and trading there gives 2% trade price improvement.
const (
	settlementRestockTicks = 30 * clock.TicksPerDay
	settlementPriceCenti   = 200
)

// SettlementStock is one world's authoritative, shared faction-base stock.
// Preserved stores the actual properties of goods sold to the settlement;
// entries generated by the base's stock definition have default properties.
type SettlementStock struct {
	Tile, FactionID int
	Stock           trade.Stock
	RestockAt       uint64
	Epoch           uint64
	Preserved       []item.Stack
}

func (m SettlementStock) Clone() SettlementStock {
	m.Stock.Lines = slices.Clone(m.Stock.Lines)
	m.Preserved = slices.Clone(m.Preserved)
	return m
}

// CloneMarkets copies every market, including its mutable stock and
// preserved physical items, for a save or a restored world.
func CloneMarkets(markets []SettlementStock) []SettlementStock {
	if len(markets) == 0 {
		return nil
	}
	out := make([]SettlementStock, len(markets))
	for i, m := range markets {
		out[i] = m.Clone()
	}
	return out
}

// marketIndex locates the single authoritative record without copying it.
// Callers mutate it only inside the simulation's command pass.
func (f marketOps) marketIndex(tile int) (int, bool) {
	if f.market == nil {
		return 0, false
	}
	return slices.BinarySearchFunc(*f.market, tile, func(m SettlementStock, t int) int {
		if m.Tile < t {
			return -1
		}
		if m.Tile > t {
			return 1
		}
		return 0
	})
}

// MarketAt is a snapshot of the existing market, safe for read-only callers.
func (f marketOps) MarketAt(tile int) (SettlementStock, bool) {
	i, ok := f.marketIndex(tile)
	if !ok {
		return SettlementStock{}, false
	}
	return (*f.market)[i].Clone(), true
}

// VisitMarket creates or restocks a single visited settlement. Its seed is
// independent of the simulation's trade, story and world RNG streams.
func (f marketOps) VisitMarket(tile int, fa *faction.Faction, now uint64) {
	if f.market == nil || fa == nil || fa.Defeated || !fa.Type.Human() || fa.Relation == faction.Hostile {
		return
	}
	i, ok := f.marketIndex(tile)
	epoch, restockAt := uint64(0), now+settlementRestockTicks
	if ok {
		cur := (*f.market)[i]
		if cur.FactionID == fa.ID && now < cur.RestockAt {
			return
		}
		epoch, restockAt = cur.Epoch, cur.RestockAt
		if cur.FactionID != fa.ID {
			epoch, restockAt = 0, now+settlementRestockTicks
		} else {
			advance := uint64(1) + (now-restockAt)/settlementRestockTicks
			epoch += advance
			restockAt += advance * settlementRestockTicks
		}
	}
	seed := uint64(0)
	if p := f.h.Planet(); p != nil {
		seed = p.Seed
	}
	seed = randx.Mix64(seed ^ randx.Mix64(uint64(tile)+0x736574746c65) ^ randx.Mix64(epoch+0x6d61726b6574))
	m := SettlementStock{
		Tile: tile, FactionID: fa.ID, Epoch: epoch, RestockAt: restockAt,
		Stock: trade.GenerateSettlement(faction.DefOf(fa.Type).Tech, seed),
	}
	if ok {
		(*f.market)[i] = m
	} else {
		*f.market = slices.Insert(*f.market, i, m)
	}
}

func (f marketOps) clearMarket(tile int) {
	if i, ok := f.marketIndex(tile); ok {
		*f.market = slices.Delete(*f.market, i, i+1)
	}
}

// takeStock builds the purchased physical stacks from the base's current
// stock. The caller works on a clone and commits it only after cargo passes
// preflight. Existing sold stacks keep all their physical attributes.
func takeStock(m *SettlementStock, lines []trade.Line) []item.Stack {
	var bought []item.Stack
	for _, l := range lines {
		remain := l.Qty
		for i := 0; i < len(m.Preserved) && remain > 0; {
			st := &m.Preserved[i]
			if st.Kind != l.Kind || st.Building != l.Building {
				i++
				continue
			}
			n := min(st.Qty, remain)
			part := *st
			part.Qty = n
			bought = append(bought, part)
			st.Qty -= n
			remain -= n
			if st.Qty == 0 {
				m.Preserved = slices.Delete(m.Preserved, i, i+1)
			} else {
				i++
			}
		}
		if remain > 0 {
			bought = append(bought, item.Stack{
				Kind: l.Kind, Qty: remain, Building: l.Building,
				Stuff: trade.CrateStuff(l.Building),
			})
		}
		m.Stock.AddGoods(l.Goods(), -l.Qty)
	}
	return bought
}

// preserveSale joins only stacks with identical physical attributes.
func preserveSale(m *SettlementStock, st item.Stack) {
	st.X, st.Y, st.Carrier = 0, 0, 0
	for i := range m.Preserved {
		candidate := m.Preserved[i]
		candidate.Qty = st.Qty
		if candidate == st {
			m.Preserved[i].Qty += st.Qty
			return
		}
	}
	m.Preserved = append(m.Preserved, st)
}

// Trade validates a caravan at its actual visited tile and performs an
// all-or-nothing exchange against the settlement's shared inventory.
// Target tile and prices are always server-derived.
func (f marketOps) Trade(cid uint64, negotiator entity.EntityID, encoded string, gift bool) (trade.Result, string) {
	refuse := func(reason string, reject trade.Reject) (trade.Result, string) {
		f.h.Note("%s", reason)
		return trade.Result{Reject: reject}, reason
	}
	c := (Fleet{marketOps: f}).At(entity.EntityID(cid))
	if c == nil || c.Back || c.C.State != caravan.Visiting || f.h.Now() >= c.C.VisitUntil || c.Ask.Letter != 0 {
		return refuse("The caravan is not visiting a settlement.", trade.RejectUnwanted)
	}
	fa := f.h.Faction(c.C.Tile)
	if fa == nil || fa.Defeated || !fa.Type.Human() || fa.Relation == faction.Hostile || fa.Besieged || !slices.Contains(fa.Settlements, c.C.Tile) {
		return refuse("The settlement cannot trade.", trade.RejectHostile)
	}
	if !slices.Contains(c.C.Members, uint64(negotiator)) || !f.h.Alive(negotiator) || !f.h.Standing(negotiator) ||
		f.h.Breaking(negotiator) || f.h.Capacity(negotiator, body.Talking) <= 0 {
		return refuse("No caravan member can negotiate this trade.", trade.RejectUnwanted)
	}
	if f.market == nil {
		return refuse("The settlement market is unavailable.", trade.RejectUnwanted)
	}
	i, ok := f.marketIndex(c.C.Tile)
	if !ok || (*f.market)[i].FactionID != fa.ID {
		return refuse("The settlement has no stock.", trade.RejectUnwanted)
	}
	deltas, err := trade.DecodeOffer(encoded)
	if err != nil {
		return refuse("The trade offer is invalid.", trade.RejectUnwanted)
	}
	if !gift {
		for _, d := range deltas {
			if d.Kind == item.Silver {
				return refuse("Silver is settled by the trader.", trade.RejectUnwanted)
			}
		}
	}
	m := &(*f.market)[i]
	cargo := f.h.MarketCargo()
	res := trade.Settle(deltas, cargo.TradeCounts(cid), m.Stock, trade.Terms{
		Social: f.h.SocialLevel(negotiator), Goodwill: fa.Goodwill,
		Hostile: fa.Relation == faction.Hostile, ImproveCenti: settlementPriceCenti,
	}, gift)
	if !res.OK() {
		return refuse(res.Reject.String(), res.Reject)
	}
	next := m.Clone()
	incoming := takeStock(&next, res.Buy)
	plan, why := cargo.PlanTrade(cid, len(c.C.Members), res, incoming)
	if why != "" {
		return refuse(why, trade.RejectOverStock)
	}
	next.Stock.Silver -= res.Silver
	for _, st := range plan.Sold() {
		if st.Kind == item.Silver {
			next.Stock.Silver += st.Qty
			continue
		}
		next.Stock.Add(st.Kind, st.Qty)
		preserveSale(&next, st)
	}
	// A gift of silver has no priced trade balance; its payment also moves
	// to the settlement's physical silver stock.
	if gift {
		for _, d := range deltas {
			if d.Kind == item.Silver && d.Qty < 0 {
				next.Stock.Silver -= d.Qty
			}
		}
	}
	cargo.CommitTrade(cid, plan)
	(*f.market)[i] = next
	(Fleet{marketOps: f}).pace(c) // purchased cargo changes the return speed
	if gift && res.Goodwill != 0 {
		faction.Adjust(fa, res.Goodwill, fmt.Sprintf("Day %d: caravan gifts (%+d goodwill)", f.h.Day(), res.Goodwill))
	}
	f.h.Note("The caravan traded with %s.", f.h.TileName(c.C.Tile))
	return res, ""
}
